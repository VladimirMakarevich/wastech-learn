// ESLint owns correctness, Prettier owns formatting: eslint-config-prettier (last in the list) switches
// off every stylistic rule that would fight `prettier --check`.
//
// The package boundaries of the headless core are enforced here, so a layering violation fails
// `npm run lint:es` and CI instead of waiting for a review.
// The globs already cover packages that do not exist yet; each one starts linted the moment its folder
// appears. Later blocks replace a rule's options for the files they match, so every package block repeats
// the syntax bans it still needs.
import { builtinModules } from "node:module";
import js from "@eslint/js";
import comments from "@eslint-community/eslint-plugin-eslint-comments/configs";
import { defineConfig } from "eslint/config";
import angular from "angular-eslint";
import prettier from "eslint-config-prettier";
import globals from "globals";
import tseslint from "typescript-eslint";

/**
 * @typedef {{ name: string, message: string }} RestrictedPath
 * @typedef {{ group: string[], message: string }} RestrictedPattern
 * @typedef {{ paths?: RestrictedPath[], patterns?: RestrictedPattern[] }} Restriction
 */

// Every Node built-in, bare (`fs`, `fs/promises`, `worker_threads`) and prefixed (`node:sqlite`), taken from
// the running Node so the list never goes stale. Bare names are matched exactly, so a package such as
// `@noble/hashes/crypto` is not mistaken for one.
const BARE_BUILTINS = builtinModules.filter(
  (name) => !name.startsWith("node:"),
);
const NODE_MESSAGE =
  "This package also runs in the browser: Node APIs belong in content-fs or a host.";
/** @type {Restriction} */
const NODE_APIS = {
  paths: BARE_BUILTINS.map((name) => ({ name, message: NODE_MESSAGE })),
  patterns: [{ group: ["node:*"], message: NODE_MESSAGE }],
};
const NODE_DYNAMIC_IMPORT = {
  selector: `ImportExpression[source.value=/^(node:.*|${BARE_BUILTINS.map((name) => name.replace("/", "\\/")).join("|")})$/]`,
  message: NODE_MESSAGE,
};

const HOST_NAMES = ["cli", "mcp-server", "server", "app"];
const TABLE_MESSAGE =
  "Packages depend downward only: core and srs on nothing of ours, session on both, content-fs on the three, Node hosts on all four, the app on core, srs and session.";
/** @param {string} name @returns {Restriction} */
const pkg = (name) => ({
  paths: [{ name: `@wastech-learn/${name}`, message: TABLE_MESSAGE }],
  patterns: [{ group: [`@wastech-learn/${name}/*`], message: TABLE_MESSAGE }],
});

/**
 * @param {...Restriction} parts
 * @returns {import("eslint").Linter.RulesRecord}
 */
const restrictImports = (...parts) => ({
  "no-restricted-imports": [
    "error",
    {
      paths: parts.flatMap((p) => p.paths ?? []),
      patterns: parts.flatMap((p) => p.patterns ?? []),
    },
  ],
});

const NO_ENUM = {
  selector: "TSEnumDeclaration",
  message: "Use a const object or a union of literals instead of an enum.",
};
const NO_DEFAULT_EXPORT = {
  selector: "ExportDefaultDeclaration",
  message: "Use named exports; default exports only in tool configs.",
};
/** @param {...{ selector: string, message: string }} bans @returns {import("eslint").Linter.RulesRecord} */
const restrictSyntax = (...bans) => ({
  "no-restricted-syntax": ["error", ...bans],
});

export default defineConfig(
  {
    ignores: [
      "**/node_modules/**",
      "**/dist/**",
      "**/coverage/**",
      // tsc -b output for tsconfig.tooling.json.
      ".cache/**",
      // Generated by prototypes/desktop-ui/build-data.mjs from the content repo.
      "prototypes/desktop-ui/data.js",
      // The Angular builder's cache and Playwright's reports.
      "**/.angular/**",
      "test-results/**",
      "playwright-report/**",
      // Third-party Impeccable skill: bundled browser scripts, updated by its installer.
      ".agents/skills/impeccable/**",
      ".claude/skills/impeccable/**",
    ],
  },
  // A disable that silences nothing is an error, and every disable says why (`-- reason`).
  {
    linterOptions: {
      reportUnusedDisableDirectives: "error",
      reportUnusedInlineConfigs: "error",
    },
  },
  js.configs.recommended,
  comments.recommended,
  {
    rules: { "@eslint-community/eslint-comments/require-description": "error" },
  },

  // TypeScript: strict and type-aware. Every package brings its own tsconfig; the project service finds it.
  {
    files: ["**/*.{ts,mts,cts,tsx}"],
    extends: [
      tseslint.configs.strictTypeChecked,
      tseslint.configs.stylisticTypeChecked,
    ],
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      "@typescript-eslint/consistent-type-imports": "error",
      "@typescript-eslint/switch-exhaustiveness-check": "error",
      "@typescript-eslint/explicit-module-boundary-types": "error",
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT),
    },
  },
  {
    // Tests may reach into fixtures with non-null assertions; the shape is known by construction.
    files: ["**/*.test.{ts,mts}", "**/test/**/*.{ts,mts}"],
    rules: { "@typescript-eslint/no-non-null-assertion": "off" },
  },

  // Node scripts and tool configs (ESM). Plain .js outside the repository root is not Node by default.
  {
    files: ["**/*.{mjs,cjs}", "*.js", "scripts/**/*.js"],
    languageOptions: { ecmaVersion: "latest", globals: globals.node },
  },
  // The prototype runs in the browser as a classic script next to the generated data.js.
  {
    files: ["prototypes/**/*.js"],
    languageOptions: { sourceType: "script", globals: globals.browser },
  },

  // Package boundaries (headless core). core and srs depend on nothing of ours and on no Node API.
  {
    files: ["packages/core/**"],
    rules: {
      ...restrictImports(
        NODE_APIS,
        pkg("srs"),
        pkg("session"),
        pkg("content-fs"),
        ...HOST_NAMES.map(pkg),
      ),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT, NODE_DYNAMIC_IMPORT),
    },
  },
  {
    files: ["packages/srs/**"],
    rules: {
      ...restrictImports(
        NODE_APIS,
        pkg("core"),
        pkg("session"),
        pkg("content-fs"),
        ...HOST_NAMES.map(pkg),
      ),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT, NODE_DYNAMIC_IMPORT),
    },
  },
  // session joins core and srs for every host that runs a review, the browser included: still no Node API.
  {
    files: ["packages/session/**"],
    rules: {
      ...restrictImports(NODE_APIS, pkg("content-fs"), ...HOST_NAMES.map(pkg)),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT, NODE_DYNAMIC_IMPORT),
    },
  },
  {
    files: ["packages/content-fs/**"],
    rules: restrictImports(...HOST_NAMES.map(pkg)),
  },
  // Hosts on Node may use the core and content-fs, never another host or the app. The one exception is the
  // CLI's `serve`, which starts the local server: the server is a library the CLI runs, not a peer it reaches into.
  ...["cli", "mcp-server", "server"].map((host) => ({
    files: [`packages/${host}/**`],
    rules: restrictImports(
      ...HOST_NAMES.filter(
        (other) => other !== host && !(host === "cli" && other === "server"),
      ).map(pkg),
    ),
  })),
  // The app runs in the browser: core types, the srs queue and the session engine, state through ReviewStore.
  {
    files: ["packages/app/**"],
    rules: {
      ...restrictImports(
        NODE_APIS,
        pkg("content-fs"),
        ...["cli", "mcp-server", "server"].map(pkg),
      ),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT, NODE_DYNAMIC_IMPORT),
    },
  },

  // The app's end-to-end scenarios drive a browser from Node: they prepare a content copy with content-fs and
  // start the CLI, so Node APIs and content-fs are theirs to use.
  {
    files: ["packages/app/e2e/**"],
    rules: {
      ...restrictImports(...["cli", "mcp-server", "server"].map(pkg)),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT),
      // Playwright reads a fixture's dependencies from its destructured first argument, `{}` for none.
      "no-empty-pattern": "off",
    },
  },

  // The app's unit tests run in Node over its pure modules; the literal audit reads the templates from disk.
  {
    files: ["packages/app/test/**"],
    rules: {
      ...restrictImports(
        pkg("content-fs"),
        ...["cli", "mcp-server", "server"].map(pkg),
      ),
      ...restrictSyntax(NO_ENUM, NO_DEFAULT_EXPORT),
    },
  },

  // Angular: component and template rules, accessibility included, for the TypeScript of the app and the
  // templates inline in its components.
  {
    files: ["packages/app/src/**/*.ts"],
    extends: [angular.configs.tsRecommended],
    processor: /** @type {import("eslint").Linter.Processor} */ (
      angular.processInlineTemplates
    ),
    rules: {
      "@angular-eslint/component-selector": [
        "error",
        { type: "element", prefix: "wl", style: "kebab-case" },
      ],
      "@angular-eslint/directive-selector": [
        "error",
        { type: "attribute", prefix: "wl", style: "camelCase" },
      ],
      "@angular-eslint/prefer-on-push-component-change-detection": "error",
      // A component or a service is a decorated class, empty while its template does the work.
      "@typescript-eslint/no-extraneous-class": [
        "error",
        { allowWithDecorator: true },
      ],
    },
  },
  {
    files: ["packages/app/src/**/*.html"],
    extends: [
      angular.configs.templateRecommended,
      angular.configs.templateAccessibility,
    ],
  },

  // Tool configs (vitest.config.ts and friends) export a default, run on Node and live outside the
  // packages' tsconfig, so they are linted without type information. Last, so it wins over the blocks above.
  {
    files: ["**/*.config.{ts,mts,cts}"],
    extends: [tseslint.configs.disableTypeChecked],
    rules: { "no-restricted-imports": "off", ...restrictSyntax(NO_ENUM) },
  },

  prettier,
);
